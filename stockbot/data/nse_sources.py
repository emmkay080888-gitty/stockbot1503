def _save_cache(data: dict[str, list[str]]):
    """Save NSE constituents to JSON cache."""
    try:
        CACHE_FILE.parent.mkdir(parents=True, exist_ok=True)
        with open(CACHE_FILE, "w") as f:
            json.dump(data, f, indent=2)
    except Exception as e:
        logger.warning(f"Failed to save NSE cache: {e}")


def get_nse_constituents(force_refresh: bool = False) -> dict[str, list[str]]:
    """Get NSE index constituents.

    Priority:
    1. Cache file (fast, no network)
    2. Hardcoded fallback lists (always available)
    3. NSE API (only if force_refresh=True — slow, may fail)

    The NSE API is NOT called on normal startup to avoid blocking.
    Use refresh_constituents() explicitly to fetch from NSE API.

    Returns:
        dict mapping index_key -> list of ticker symbols (with .NS suffix)
    """
    # Try cache first (fast, no network)
    if not force_refresh:
        cached = _get_cached()
        if cached:
            logger.info("Using cached NSE constituents")
            return cached
        # No cache — use hardcoded lists (instant, no API call)
        logger.info("Using hardcoded NSE constituent lists")
        return _get_hardcoded_constituents()

    # force_refresh=True: try NSE API (slow, may block)
    logger.info("Fetching NSE constituents from API (force_refresh)...")
    api_data = _try_fetch_from_nse()
    if api_data:
        _save_cache(api_data)
        return api_data

    # API failed — fall back to hardcoded
    logger.warning("NSE API unavailable, using hardcoded lists")
    return _get_hardcoded_constituents()


def _get_hardcoded_constituents() -> dict[str, list[str]]:
    """Return the hardcoded fallback constituent lists."""
    return {
        "nifty50": NIFTY50,
        "nifty_next50": NIFTY_NEXT50,
        "nifty200": NIFTY200,
        "nifty500": NIFTY500,
        "nifty_midcap150": NIFTY_MIDCAP150,
        "nifty_smallcap250": NIFTY_SMALLCAP250,
        "nifty_midsml400": NIFTY_MIDSML400,
        "nifty_bank": NIFTY_BANK,
    }


def refresh_constituents() -> bool:
    """Force refresh the NSE constituent lists from NSE API.

    Returns True if successful, False if fell back to hardcoded.
    """
    data = _try_fetch_from_nse()
    if data:
        _save_cache(data)
        logger.info(f"NSE constituents refreshed: {len(data)} indices")
        return True
    logger.warning("NSE API unavailable, using hardcoded lists")
    return False


